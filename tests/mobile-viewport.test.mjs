import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFile} from 'node:fs/promises';
const source=await readFile(new URL('../flow/mobile-navigation.js',import.meta.url),'utf8');
const c=vm.createContext({});
vm.runInContext(source.slice(source.indexOf('function installMimineNavViewport'),source.lastIndexOf('installMimineNavViewport({win:window')),c);
const events=new Map(),frames=[];let inset=0,mobile=true,editing=false,layoutBottom=844;
const viewport={height:790,offsetTop:0,scale:1,addEventListener:(name,fn)=>events.set(name,fn)};
const nav={getBoundingClientRect:()=>({bottom:layoutBottom-inset})};
const doc={getElementById:()=>nav,activeElement:{matches:()=>editing},documentElement:{style:{setProperty:(key,value)=>{assert.equal(key,'--mobile-nav-inset');inset=parseFloat(value);}}},addEventListener:(name,fn)=>events.set(name,fn)};
const win={visualViewport:viewport,matchMedia:()=>({matches:mobile}),requestAnimationFrame:fn=>frames.push(fn),addEventListener:(name,fn)=>events.set(name,fn)};
const flush=()=>{while(frames.length)frames.shift()();};
c.installMimineNavViewport({win,doc});flush();
assert.equal(inset,54,'Browser controls must not cover the navigation');
events.get('scroll')();flush();assert.equal(inset,54,'Repeated viewport events must not drift');
viewport.height=844;events.get('resize')();flush();assert.equal(inset,0,'Restore the bottom when browser controls retract');
layoutBottom=790;viewport.height=790;events.get('resize')();flush();assert.equal(inset,0,'A browser that already resizes fixed elements must not add a second gap');
layoutBottom=844;viewport.height=500;viewport.offsetTop=30;events.get('scroll')();flush();assert.equal(inset,314);
editing=true;events.get('focusin')();flush();assert.equal(inset,0,'Do not place tabs over the keyboard');
editing=false;viewport.height=790;viewport.offsetTop=0;events.get('focusout')();flush();assert.equal(inset,54);
viewport.scale=2;events.get('resize')();flush();assert.equal(inset,0,'Do not reposition tabs during pinch zoom');
viewport.scale=1;mobile=false;events.get('resize')();flush();assert.equal(inset,0);
c.installMimineNavViewport({win:{},doc:{}});
console.log('Mobile viewport: toolbar occlusion, stable resize, native fixed sizing, keyboard, zoom and desktop guards passed.');
