import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';
const db=new PGlite();
await db.exec(`create role anon;create role authenticated;create role service_role;create schema auth;
create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
create table app_users(user_id uuid primary key,is_active boolean);
create table product_categories(id bigint primary key,name text,is_active boolean default true);
create table products(id bigint generated always as identity primary key,name text not null,category text,category_id bigint,sku text,purchase_price bigint,sale_price bigint,low_stock_threshold integer,updated_at timestamptz default now());
create table expenses(id bigint generated always as identity primary key,expense_date date,category text,amount bigint,memo text,updated_at timestamptz default now());
create table product_purchase_batches(id bigint generated always as identity primary key,product_id bigint references products, purchase_date date,expiration_date date,quantity integer,remaining_quantity integer,unit_cost bigint,supplier text,memo text);
grant usage on schema public,auth to authenticated,anon;
grant select on app_users,product_categories to authenticated;
grant all on products,expenses,product_purchase_batches to authenticated;
insert into app_users values('11111111-1111-4111-8111-111111111111',true),('22222222-2222-4222-8222-222222222222',false);
set request.jwt.claim.sub='11111111-1111-4111-8111-111111111111';`);
await db.exec(await readFile(new URL('../supabase/flow-stock-receipts.sql',import.meta.url),'utf8'));
await db.exec('set role authenticated');
const id=n=>`33333333-3333-4333-8333-${String(n).padStart(12,'0')}`;
const scalar=async(sql,args=[])=>Object.values((await db.query(sql,args)).rows[0])[0];
const receive=(n,doc)=>scalar('select mimine_receive_stock($1,$2)',[id(n),doc]);
const date='2026-11-03';
const item={name:'검증 라면',barcode:'2000000000015',category:'라면',qty:2,cost:810,price:4000,expiry:'2027-05-01'};
const created=await receive(1,{type:'product',date,items:[item]});
const productId=created.items[0].productId;
assert.equal(await scalar('select sum(remaining_quantity)::int from product_purchase_batches'),2);
assert.equal((await receive(1,{type:'product',date,items:[item]})).duplicate,true);
assert.equal(await scalar('select count(*)::int from products'),1);
await receive(2,{type:'inbound',date,items:[{productId,qty:3,cost:820,price:4200,expiry:'2027-06-01'}],addExpense:true});
assert.equal(await scalar('select sale_price::int from products'),4200);
assert.equal(await scalar('select sum(remaining_quantity)::int from product_purchase_batches'),5);
assert.equal(await scalar('select sum(amount)::int from expenses'),2460);
const receipt={type:'receipt',date,fingerprint:'same-image-fingerprint',supplier:'검증 구매처',total:1620,items:[{productId,qty:2,cost:810,price:4200,expiry:'2027-07-01'}],addExpense:true};
await receive(3,receipt);
assert.equal((await receive(4,receipt)).duplicate,true);
assert.equal(await scalar('select sum(remaining_quantity)::int from product_purchase_batches'),7);
assert.equal(await scalar('select count(*)::int from expenses'),2);
assert.equal(await scalar('select sum(amount)::int from expenses'),4080);
const batchesBefore=await scalar('select count(*)::int from product_purchase_batches');
await assert.rejects(receive(5,{...receipt,fingerprint:'bad-second-item',items:[{productId,qty:1,cost:999,price:8000},{name:'잘못된 품목',qty:0,cost:100,price:200}]}),/수량/);
assert.equal(await scalar('select count(*)::int from product_purchase_batches'),batchesBefore);
assert.equal(await scalar('select sale_price::int from products'),4200);
assert.equal(await scalar('select count(*)::int from mimine_stock_documents'),3);
await assert.rejects(receive(6,{...receipt,fingerprint:'discount',total:1500}),/합계 차이/);
await receive(6,{...receipt,fingerprint:'discount',total:1500,adjustmentConfirmed:true});
assert.equal(await scalar("select amount::int from expenses order by id desc limit 1"),1500);
const payload={date,amount:1234,vendor:'검증 비용',category:'소모품',note:'메모'};
await scalar('select mimine_save_expense($1,$2)',[id(10),payload]);
assert.equal((await scalar('select mimine_save_expense($1,$2)',[id(10),payload])).duplicate,true);
assert.equal(await scalar("select count(*)::int from expenses where amount=1234"),1);
const supplyItem={name:'검증 주방세제',category:'청소용품',qty:1,cost:3000,price:0};
const supplyResult=await receive(20,{type:'receipt',date,fingerprint:'store-supplies',supplier:'검증 마트',total:3000,items:[supplyItem],addExpense:false});
assert.equal(await scalar('select sale_price::int from products where id=$1',[Number(supplyResult.items[0].productId)]),0);
await assert.rejects(receive(21,{type:'product',date,items:[{name:'판매상품 0원 검증',category:'라면',qty:1,cost:100,price:0}]}),/판매가/);
await db.exec("set request.jwt.claim.sub='22222222-2222-4222-8222-222222222222'");
await assert.rejects(receive(7,{type:'inbound',date,items:[{productId,qty:1,cost:100,price:1000}]}),/활성 사용자/);
await db.exec('reset role;set role anon');
await assert.rejects(receive(8,{type:'inbound',date,items:[{productId,qty:1,cost:100,price:1000}]}),/permission denied/);
await assert.rejects(db.query('select * from mimine_stock_documents'),/permission denied/);
await db.close();
console.log('Stock SQL: atomic rollback, latest sale price, receipt fingerprint/request dedupe, single expense, confirmed discount and access controls passed.');
